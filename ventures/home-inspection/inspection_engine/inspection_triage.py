"""Internal, evidence-linked defect reasoning and report triage. NEVER final report.

This module refuses to convert agent confidence, a source link, an uploaded
photo, or a claimed signature into a confirmed diagnosis. It preserves serious
unresolved items for qualified review instead of hiding them on uncertainty.
"""
from __future__ import annotations

from pathlib import Path
import hashlib
import json
import re

from .case_verification import evaluate_finding, validate_case_context, coverage_gaps
from .inspection_policy import active_sop_context, load_policy, policy_digest
from .source_of_truth import load_catalog
from .michigan_authority import load_authorities
from .descriptors import REQUIRED_FEATURES
from .source_of_truth import KnowledgeError

LEVELS={'immediate_safety','major','material','maintenance','unknown'}
ASSERTIONS=('guaranteed safe','no defects','code compliant','100%','root cause confirmed',
            'certified defect-free','recall confirmed','electrically safe')


def _text(obj,field,limit=500,required=True):
    value=obj.get(field,'')
    if not isinstance(value,str) or len(value)>limit or (required and not value.strip()) or any(ord(c)<32 for c in value):
        raise KnowledgeError('Invalid or missing text field '+field)
    if any(phrase in value.lower() for phrase in ASSERTIONS):
        raise KnowledgeError('Unverifiable conclusive assurance in '+field)
    return value.strip()


def case_review_queue(case:dict,findings:list[dict],root:Path, *, inspection_scope:str='unverified',
                      contracted_sop:str|None=None) -> dict:
    """Create comprehensive internal review ledger and SHORT report candidates.

    Inputs can be generated by AI and are untrusted. Source hash validation is
    delegated to the existing Michigan case verification layer. Human signoff,
    contractual scope and true visual relevance must still be verified externally.
    """
    ctx=validate_case_context(case)
    if not isinstance(findings,list) or len(findings)>1000:
        raise KnowledgeError('Findings must be a bounded list')
    expected_scope=('residential' if case['building_type']=='residential_one_two_family' else 'commercial')
    if inspection_scope not in ('unverified',expected_scope):
        raise KnowledgeError('Inspection scope conflicts with classified building occupancy')
    scope=active_sop_context(inspection_scope,case['inspection_date'],contracted_sop)
    installed_policy=load_policy()
    guides={c['system']:c for c in installed_policy['systems']}
    approved_ids={s['id'] for s in installed_policy['sources']}
    approved_ids.update(s['id'] for s in load_authorities()['sources'])
    # Any other v2 literature is still untrusted for legal case conclusions.
    approved_ids.update(s['id'] for s in load_catalog()['source_records'])
    seen=set();internal=[];review_queue=[];drafts=[]
    for index,f in enumerate(findings):
        if not isinstance(f,dict) or f.get('claim_type') not in ('visual_observation','potential_defect','cause_hypothesis','code_violation','recall_applicability'):
            raise KnowledgeError('Malformed or unsupported inspection finding')
        ident=f.get('finding_id')
        if not isinstance(ident,str) or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]{0,79}',ident) or ident in seen:
            raise KnowledgeError('Findings require unique stable identifiers')
        seen.add(ident)
        if f.get('system') not in REQUIRED_FEATURES or f.get('feature_code') not in REQUIRED_FEATURES[f['system']]:
            raise KnowledgeError('Finding outside known system/feature vocabulary')
        severity=f.get('risk_priority')
        if severity not in LEVELS:
            raise KnowledgeError('Explicit unverified risk priority is required')
        symptom=_text(f,'observed_symptom')
        significance=_text(f,'possible_significance',limit=400)
        recommended=_text(f,'recommended_next_step',limit=400)
        limits=_text(f,'material_limitations',limit=400,required=False)
        source_ids=f.get('source_ids',[])
        if not isinstance(source_ids,list) or len(source_ids)!=len(set(source_ids)) or any(not isinstance(s,str) or s not in approved_ids for s in source_ids):
            raise KnowledgeError('Unknown or duplicate source reference identifier')
        result=evaluate_finding(case,f,root)
        guide=guides[f['system']]
        evidence_good=bool(result['evidence_receipts']) and not any('evidence' in b.lower() or 'hash' in b.lower() for b in result['blockers'])
        status='REVIEW_REQUIRED' if result['status']=='EVIDENCE_LINKED_REVIEW_PENDING' else 'BLOCKED_PENDING_FOLLOWUP'
        row={'finding_id':ident,'system':f['system'],'feature_code':f['feature_code'],
             'risk_priority_unverified':severity,'observed_symptom':symptom,
             'possible_significance':significance,'alternative_explanation':guide['alternative_explanation'],
             'cause_hypotheses':f.get('cause_assessment',{}),
             'discriminating_evidence_needed':guide['what_would_distinguish'],
             'reference_ids':list(source_ids),
             'evidence_receipts':result['evidence_receipts'],'review_status':status,
             'blockers':result['blockers'],'recommended_qualified_referral':guide['qualified_referral'],
             'customer_release_allowed':False}
        internal.append(row)
        if severity in ('immediate_safety','major'):
            review_queue.append({'finding_id':ident,'urgency':'PROMPT_HUMAN_TRIAGE',
                                 'unverified_priority':severity,
                                 'action':'Have qualified inspector promptly assess concern and advise appropriate specialist; do not assert cause',
                                 'evidence_verified':evidence_good,'blockers':result['blockers']})
        elif status!='REVIEW_REQUIRED' or severity=='unknown':
            review_queue.append({'finding_id':ident,'urgency':'ROUTINE_HUMAN_FOLLOWUP',
                                 'unverified_priority':severity,'evidence_verified':evidence_good,
                                 'blockers':result['blockers']})
        # Client-report CANDIDATE only, never published, and only for evidence-linked
        # concerns. Causes, legal citations and raw differential reasoning stay internal.
        if status=='REVIEW_REQUIRED' and severity in ('immediate_safety','major','material'):
            drafts.append({'finding_id':ident,'status':'PENDING_QUALIFIED_INSPECTOR_EDIT',
                           'priority_for_inspector':severity,
                           'location':_text(f,'location',limit=120),
                           'observed_condition':symptom,'why_it_matters':significance,
                           'recommended_follow_up':recommended,
                           'material_limitation':limits,
                           'evidence_ids':[r['id'] for r in result['evidence_receipts']],
                           'not_a_cause_or_code_certification':True,'publishable':False})
    # A missing coverage feature is a follow-up task, not a spurious defect.
    gaps=coverage_gaps(case,[{'system':f['system'],'feature_code':f['feature_code'],'evidence_ids':f.get('evidence_ids',[])}
                              for f in findings if isinstance(f,dict) and f.get('system') in REQUIRED_FEATURES])
    root_payload={'case_id':case['case_id'],'finding_ids':sorted(seen),'policy_sha256':policy_digest(),
                  'inspection_date':case['inspection_date']}
    return {'schema_version':4,'case_id':case['case_id'],'scope':scope,
            'internal_reasoning_ledger':internal,'mandatory_human_review_queue':review_queue,
            'client_report_candidates_for_inspector_only':drafts,
            'system_coverage_gaps':gaps,'comprehensive_visual_coverage_verified':False,
            'qualified_inspector_approval_authenticated':False,'customer_release_allowed':False,
            'policy_sha256':policy_digest(),'case_summary_sha256':hashlib.sha256(json.dumps(root_payload,sort_keys=True).encode()).hexdigest(),
            'limitations':'Not a signed inspection, diagnosis, code-compliance evaluation, warranty, or guarantee against missed defects.'}
